import { readFile, readdir } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const LIMIT = 200;
const INCLUDE_DIRS = ['apps', 'packages'];
const EXTS = new Set(['.ts', '.tsx', '.mts', '.cts']);
const EXCLUDE_DIR_NAMES = new Set([
  'node_modules',
  'dist',
  '.next',
  '.turbo',
  'generated',
  'build',
  'coverage',
  '_reference',
  '.playwright-mcp',
]);
const EXCLUDE_PATH_FRAGMENTS = [
  '/api/endpoints/',
  '/api/model/',
  '/api/schemas/',
];
const EXCLUDE_FILE_PATTERNS = [/\.spec\.ts$/, /\.test\.ts$/, /\.d\.ts$/];

async function isGenerated(file) {
  try {
    const handle = await readFile(file, { encoding: 'utf8' });
    const head = handle.slice(0, 400);
    return /Generated by orval|@generated|do not edit manually/i.test(head);
  } catch {
    return false;
  }
}

async function walk(dir, acc) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (EXCLUDE_DIR_NAMES.has(entry.name)) continue;
      await walk(full, acc);
      continue;
    }
    if (!entry.isFile()) continue;
    const ext = entry.name.slice(entry.name.lastIndexOf('.'));
    if (!EXTS.has(ext)) continue;
    if (EXCLUDE_FILE_PATTERNS.some((re) => re.test(entry.name))) continue;
    const normalized = full.split(sep).join('/');
    if (EXCLUDE_PATH_FRAGMENTS.some((frag) => normalized.includes(frag))) continue;
    acc.push(full);
  }
  return acc;
}

async function countLines(file) {
  const content = await readFile(file, 'utf8');
  return content.length === 0 ? 0 : content.split('\n').length;
}

export async function collectFileSize(root) {
  const allFiles = [];
  for (const dir of INCLUDE_DIRS) {
    await walk(join(root, dir), allFiles);
  }
  const sized = await Promise.all(
    allFiles.map(async (file) => {
      const lines = await countLines(file);
      if (lines <= LIMIT) {
        return { path: relative(root, file).split(sep).join('/'), lines, generated: false };
      }
      const generated = await isGenerated(file);
      return { path: relative(root, file).split(sep).join('/'), lines, generated };
    }),
  );
  const violations = sized
    .filter((f) => f.lines > LIMIT && !f.generated)
    .sort((a, b) => b.lines - a.lines);
  return {
    limit: LIMIT,
    totalFiles: sized.length,
    violationsCount: violations.length,
    violations: violations.map((v) => ({ path: v.path, lines: v.lines })),
  };
}
